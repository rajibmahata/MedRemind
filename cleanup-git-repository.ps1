#!/usr/bin/env pwsh
# Git Repository Cleanup Script
# Removes bin, obj, .vs folders and other unnecessary files from Git tracking
# Usage: .\cleanup-git-repository.ps1

Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?   Git Repository Cleanup - Remove Unnecessary Files   ?" -ForegroundColor Cyan
Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Navigate to repository root
$repoRoot = "F:\rajibmahata\MedRemind"
Set-Location $repoRoot

Write-Host "?? Working in: $repoRoot" -ForegroundColor Yellow
Write-Host ""

# Function to remove from Git tracking
function Remove-FromGit {
    param(
        [string]$Pattern,
        [string]$Description
    )
    
    Write-Host "???  Removing $Description..." -ForegroundColor Cyan
    
    try {
        $output = git rm -r --cached $Pattern 2>&1
        if ($LASTEXITCODE -eq 0) {
            Write-Host "   ? Removed: $Pattern" -ForegroundColor Green
            return $true
        } else {
            Write-Host "   ??  Not found or already removed: $Pattern" -ForegroundColor Gray
            return $false
        }
    } catch {
        Write-Host "   ??  Skipped: $Pattern" -ForegroundColor Gray
        return $false
    }
}

$removedCount = 0

Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Step 1: Removing Build Artifacts" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Remove bin folders
Write-Host "?? Removing bin folders..." -ForegroundColor Cyan
$binFolders = @(
    "backend/MedRemind.API/bin/",
    "backend/MedRemind.Services/bin/",
    "backend/MedRemind.Core/bin/",
    "backend/MedRemind.Tests/bin/",
    "mobile/MedRemind.Mobile/bin/"
)

foreach ($folder in $binFolders) {
    if (Remove-FromGit $folder "bin folder") { $removedCount++ }
}

# Remove obj folders
Write-Host ""
Write-Host "?? Removing obj folders..." -ForegroundColor Cyan
$objFolders = @(
    "backend/MedRemind.API/obj/",
    "backend/MedRemind.Services/obj/",
    "backend/MedRemind.Core/obj/",
    "backend/MedRemind.Tests/obj/",
    "mobile/MedRemind.Mobile/obj/"
)

foreach ($folder in $objFolders) {
    if (Remove-FromGit $folder "obj folder") { $removedCount++ }
}

Write-Host ""
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Step 2: Removing Visual Studio Folders" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Remove .vs folder
if (Remove-FromGit ".vs/" ".vs folder") { $removedCount++ }

Write-Host ""
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Step 3: Removing Database Files" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Remove database files
$dbFiles = @(
    "*.db",
    "*.db-shm",
    "*.db-wal",
    "*.sqlite",
    "*.sqlite3",
    "backend/MedRemind.API/medremindDB.db*"
)

foreach ($pattern in $dbFiles) {
    if (Remove-FromGit $pattern "database files") { $removedCount++ }
}

Write-Host ""
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Step 4: Removing Environment Files" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Remove environment files
$envFiles = @(
    ".env",
    "backend/MedRemind.API/appsettings.Development.json",
    "mobile/MedRemind.Mobile/appsettings.json",
    "python-microservice/.env"
)

foreach ($file in $envFiles) {
    if (Remove-FromGit $file "environment file") { $removedCount++ }
}

Write-Host ""
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Step 5: Removing Storage Folders" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Remove storage folders
$storageFolders = @(
    "backend/MedRemind.API/Files/",
    "backend/MedRemind.API/OCRs/",
    "backend/MedRemind.API/Prescriptions/",
    "backend/MedRemind.API/LLMResponses/",
    "backend/MedRemind.API/Analysis/",
    "backend/MedRemind.API/Logs/",
    "python-microservice/storage/"
)

foreach ($folder in $storageFolders) {
    if (Remove-FromGit $folder "storage folder") { $removedCount++ }
}

Write-Host ""
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Step 6: Removing Python Cache" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Remove Python cache
$pythonCache = @(
    "python-microservice/__pycache__/",
    "python-microservice/.venv/",
    "python-microservice/venv/",
    "python-microservice/.pytest_cache/"
)

foreach ($folder in $pythonCache) {
    if (Remove-FromGit $folder "Python cache") { $removedCount++ }
}

Write-Host ""
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Cleanup Summary" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Check Git status
$gitStatus = git status --short
$changedFiles = ($gitStatus | Measure-Object).Count

Write-Host "?? Statistics:" -ForegroundColor Cyan
Write-Host "   Total removals attempted: $removedCount" -ForegroundColor White
Write-Host "   Files to be committed: $changedFiles" -ForegroundColor White
Write-Host ""

if ($changedFiles -gt 0) {
    Write-Host "? Cleanup completed!" -ForegroundColor Green
    Write-Host ""
    Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
    Write-Host "Next Steps" -ForegroundColor Yellow
    Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
    Write-Host ""
    Write-Host "1??  Review changes:" -ForegroundColor Cyan
    Write-Host "   git status" -ForegroundColor White
    Write-Host ""
    Write-Host "2??  Stage .gitignore:" -ForegroundColor Cyan
    Write-Host "   git add .gitignore" -ForegroundColor White
    Write-Host ""
    Write-Host "3??  Commit changes:" -ForegroundColor Cyan
    Write-Host "   git commit -m ""Remove bin, obj, .vs and unnecessary files from tracking""" -ForegroundColor White
    Write-Host ""
    Write-Host "4??  Push to remote:" -ForegroundColor Cyan
    Write-Host "   git push origin Developer" -ForegroundColor White
    Write-Host ""
    Write-Host "Would you like to proceed with commit? (Y/N): " -ForegroundColor Yellow -NoNewline
    $proceed = Read-Host
    
    if ($proceed -eq 'Y' -or $proceed -eq 'y') {
        Write-Host ""
        Write-Host "?? Staging .gitignore..." -ForegroundColor Cyan
        git add .gitignore
        
        Write-Host "?? Committing changes..." -ForegroundColor Cyan
        git commit -m "Remove bin, obj, .vs and unnecessary files from tracking

- Removed all bin/ and obj/ folders
- Removed .vs/ folder
- Removed database files (*.db, *.sqlite)
- Removed environment files (appsettings.Development.json, .env)
- Removed storage folders (Files, OCRs, Prescriptions, etc.)
- Removed Python cache (__pycache__, .venv)
- Updated .gitignore with pattern-based exclusions"
        
        Write-Host ""
        Write-Host "? Changes committed!" -ForegroundColor Green
        Write-Host ""
        Write-Host "?? Ready to push! Run:" -ForegroundColor Cyan
        Write-Host "   git push origin Developer" -ForegroundColor White
        Write-Host ""
    } else {
        Write-Host ""
        Write-Host "??  Commit skipped. You can commit manually when ready." -ForegroundColor Yellow
        Write-Host ""
    }
} else {
    Write-Host "??  No changes detected. Repository is already clean!" -ForegroundColor Gray
    Write-Host ""
}

Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Verify Cleanup" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""
Write-Host "Run these commands to verify:" -ForegroundColor Cyan
Write-Host "   git ls-files | Select-String 'bin/'" -ForegroundColor White
Write-Host "   git ls-files | Select-String 'obj/'" -ForegroundColor White
Write-Host "   git ls-files | Select-String '.vs/'" -ForegroundColor White
Write-Host ""
Write-Host "All should return nothing if cleanup was successful." -ForegroundColor Gray
Write-Host ""
Write-Host "? Script completed!" -ForegroundColor Green
Write-Host ""
