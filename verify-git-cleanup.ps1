#!/usr/bin/env pwsh
# Verification Script - Check if cleanup was successful
# Usage: .\verify-git-cleanup.ps1

Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?      Git Cleanup Verification Script                  ?" -ForegroundColor Cyan
Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$repoRoot = "F:\rajibmahata\MedRemind"
Set-Location $repoRoot

$totalIssues = 0
$allPassed = $true

# Function to check if pattern exists in tracked files
function Test-Pattern {
    param(
        [string]$Pattern,
        [string]$Description
    )
    
    $matches = git ls-files | Select-String $Pattern
    $count = ($matches | Measure-Object).Count
    
    if ($count -gt 0) {
        Write-Host "   ? FAIL: Found $count tracked file(s) matching '$Pattern'" -ForegroundColor Red
        if ($count -le 5) {
            $matches | ForEach-Object { Write-Host "      - $_" -ForegroundColor Gray }
        }
        return $false
    } else {
        Write-Host "   ? PASS: No tracked files matching '$Pattern'" -ForegroundColor Green
        return $true
    }
}

# Function to test .gitignore is working
function Test-GitIgnore {
    param(
        [string]$Path
    )
    
    $result = git check-ignore -v $Path 2>&1
    if ($LASTEXITCODE -eq 0) {
        Write-Host "   ? PASS: '$Path' is properly ignored" -ForegroundColor Green
        Write-Host "      Rule: $result" -ForegroundColor Gray
        return $true
    } else {
        Write-Host "   ? FAIL: '$Path' is NOT ignored" -ForegroundColor Red
        return $false
    }
}

Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Test 1: Check Tracked Files" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

Write-Host "?? Checking for bin/ folders..." -ForegroundColor Cyan
if (-not (Test-Pattern "bin/" "bin folders")) { $totalIssues++; $allPassed = $false }

Write-Host ""
Write-Host "?? Checking for obj/ folders..." -ForegroundColor Cyan
if (-not (Test-Pattern "obj/" "obj folders")) { $totalIssues++; $allPassed = $false }

Write-Host ""
Write-Host "?? Checking for .vs/ folder..." -ForegroundColor Cyan
if (-not (Test-Pattern "\.vs/" ".vs folder")) { $totalIssues++; $allPassed = $false }

Write-Host ""
Write-Host "?? Checking for database files..." -ForegroundColor Cyan
if (-not (Test-Pattern "\.db" "database files")) { $totalIssues++; $allPassed = $false }

Write-Host ""
Write-Host "?? Checking for environment files..." -ForegroundColor Cyan
if (-not (Test-Pattern "appsettings\.Development\.json" "appsettings.Development.json")) { $totalIssues++; $allPassed = $false }

Write-Host ""
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Test 2: Check .gitignore Rules" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

Write-Host "?? Testing .gitignore patterns..." -ForegroundColor Cyan
Write-Host ""

# Test various paths
$testPaths = @(
    "backend/MedRemind.API/bin/Debug/net10.0/MedRemind.API.dll",
    "backend/MedRemind.API/obj/Debug/net10.0/MedRemind.API.pdb",
    ".vs/MedRemind/v17/.suo"
)

foreach ($path in $testPaths) {
    if (-not (Test-GitIgnore $path)) { $totalIssues++; $allPassed = $false }
    Write-Host ""
}

Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Test 3: Check Git Status" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$status = git status --short
$changedFiles = ($status | Measure-Object).Count

Write-Host "?? Checking repository status..." -ForegroundColor Cyan
if ($changedFiles -eq 0) {
    Write-Host "   ? PASS: Working tree is clean" -ForegroundColor Green
} else {
    Write-Host "   ??  WARNING: $changedFiles uncommitted change(s)" -ForegroundColor Yellow
    Write-Host ""
    Write-Host "   Uncommitted files:" -ForegroundColor Gray
    $status | ForEach-Object { Write-Host "      $_" -ForegroundColor Gray }
}

Write-Host ""
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Test 4: Build Test" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

Write-Host "?? Testing build (creates bin/obj)..." -ForegroundColor Cyan
Push-Location backend/MedRemind.API
$buildOutput = dotnet build --no-restore 2>&1 | Out-String
Pop-Location

if ($LASTEXITCODE -eq 0) {
    Write-Host "   ? PASS: Build succeeded" -ForegroundColor Green
    
    # Check if new bin/obj are tracked
    Write-Host ""
    Write-Host "?? Checking if new build artifacts are ignored..." -ForegroundColor Cyan
    $statusAfterBuild = git status --short
    $newFiles = ($statusAfterBuild | Measure-Object).Count
    
    if ($newFiles -eq 0) {
        Write-Host "   ? PASS: Build artifacts are properly ignored" -ForegroundColor Green
    } else {
        Write-Host "   ? FAIL: Build created tracked files!" -ForegroundColor Red
        $statusAfterBuild | ForEach-Object { Write-Host "      $_" -ForegroundColor Gray }
        $totalIssues++
        $allPassed = $false
    }
} else {
    Write-Host "   ??  WARNING: Build failed (may be unrelated to cleanup)" -ForegroundColor Yellow
}

Write-Host ""
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Summary" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

if ($allPassed -and $totalIssues -eq 0) {
    Write-Host "?? ALL TESTS PASSED!" -ForegroundColor Green
    Write-Host ""
    Write-Host "   ? No unnecessary files tracked" -ForegroundColor Green
    Write-Host "   ? .gitignore is working correctly" -ForegroundColor Green
    Write-Host "   ? Build artifacts are ignored" -ForegroundColor Green
    Write-Host ""
    Write-Host "Your repository is clean and ready! ??" -ForegroundColor Cyan
} else {
    Write-Host "? CLEANUP INCOMPLETE" -ForegroundColor Red
    Write-Host ""
    Write-Host "   Issues found: $totalIssues" -ForegroundColor Red
    Write-Host ""
    Write-Host "Run the cleanup script to fix:" -ForegroundColor Yellow
    Write-Host "   .\cleanup-git-repository.ps1" -ForegroundColor White
}

Write-Host ""
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Additional Information" -ForegroundColor Yellow
Write-Host "????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$trackedCount = (git ls-files | Measure-Object).Count
Write-Host "?? Statistics:" -ForegroundColor Cyan
Write-Host "   Total tracked files: $trackedCount" -ForegroundColor White
Write-Host "   Uncommitted changes: $changedFiles" -ForegroundColor White
Write-Host "   Issues found: $totalIssues" -ForegroundColor White
Write-Host ""

Write-Host "? Verification complete!" -ForegroundColor Green
Write-Host ""
